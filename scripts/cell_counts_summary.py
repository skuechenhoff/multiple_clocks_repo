"""
One place for every human single-unit count the manuscript uses, computed
from the tables the reported analyses read (never typed in by hand).
(2026-11-23)

    python scripts/cell_counts_summary.py
    -> derivatives/CELL_COUNTS.md and derivatives/cell_counts.json

Sources (change here when a reported run is replaced):
    labels      ROI_assignment/cells_step5_final_labels.csv, column atlas_roi
    patients    demographics_2026-10-10/patient_demographics_summary.json
    RSA (Fig 2d)        DSR_RSA_simple_ROI/2026-08-31_17-57-30
    per-lag (Fig 3c)    per_lag_loopsets_2026-11-23/per_repeat/execute
    gradient (Fig 3d)   cell_gradient_master/2026-11-23_14-22-23_per_repeat_execute
    ripple content (Fig 4h)  swr/phase_contrast_2026-09-30/per_session.csv

@author: Svenja Kuchenhoff
"""
import os
import sys
import json
import datetime

import pandas as pd

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)
from mc.analyse.roi_labels import final_labels, FINAL_ROI_TABLE, ROI_COLUMN, read_per_cell_table

D = "/Users/xpsy1114/Documents/projects/multiple_clocks/data/ephys_humans/derivatives"
G = os.path.join(D, "group")
ROIS = ["EC", "HC_anterior", "HC_mid", "mOFC", "mPFC", "PCC"]
NAMES = {"EC": "EC", "HC_anterior": "aHC", "HC_mid": "mHC", "mOFC": "mOFC",
         "mPFC": "mPFC", "PCC": "PCC"}
SRC = dict(
    demographics=os.path.join(D, "demographics_2026-10-10", "patient_demographics_summary.json"),
    rsa=os.path.join(G, "DSR_RSA_simple_ROI", "2026-08-31_17-57-30", "roi_electrode_coords.csv"),
    per_lag=os.path.join(G, "per_lag_loopsets_2026-11-23", "per_repeat", "execute", "per_cell_ALL_ROIs.csv"),
    gradient=os.path.join(G, "cell_gradient_master", "2026-11-23_14-22-23_per_repeat_execute",
                          "final_splits", "final_splits_per_cell.csv"),
    ripple_content=os.path.join(G, "swr", "phase_contrast_2026-09-30", "per_session.csv"),
)


def by_roi(df, roi_col, subj_col):
    g = df[df[roi_col].isin(ROIS)].groupby(roi_col)
    return {r: dict(cells=int(len(x)), sessions=int(x[subj_col].nunique()))
            for r, x in g}


def counts():
    f = final_labels()
    demo = json.load(open(SRC["demographics"]))
    C = {"all": dict(qc_units=int(len(f)), in_analysis_rois=int(f.roi.isin(ROIS).sum()),
                     other=int((~f.roi.isin(ROIS)).sum()),
                     sessions=int(f.subject.nunique()),
                     patients=int(demo["n_patients"]),
                     patients_per_site={k: v["n_patients"] for k, v in demo["per_site"].items()},
                     sessions_per_site={k: v["n_sessions"] for k, v in demo["per_site"].items()}),
         "per_roi": by_roi(f, "roi", "subject")}
    other = f[~f.roi.isin(ROIS)].roi.value_counts()
    C["all"]["other_by_label"] = {k: int(v) for k, v in other.items()}
    rsa = pd.read_csv(SRC["rsa"])
    C["rsa_fig2d"] = by_roi(rsa, "roi", "subject")
    C["rsa_fig2d"]["total"] = dict(cells=int(len(rsa)), sessions=int(rsa.subject.nunique()))
    pl = read_per_cell_table(SRC["per_lag"])
    pl = pl[pl.filter(like="r_lag").notna().any(axis=1)]
    C["per_lag_fig3c"] = by_roi(pl, "roi", "subject_id")
    gr = pd.read_csv(SRC["gradient"])
    gr["site"] = gr[["MNI_x", "MNI_y", "MNI_z"]].round(3).astype(str).agg("_".join, axis=1)
    C["gradient_fig3d"] = {g: dict(cells=int((gr.pc1_ventral_dorsal_group == g).sum()),
                                   sessions=int(gr[gr.pc1_ventral_dorsal_group == g].subject_id.nunique()),
                                   sites=int(gr[gr.pc1_ventral_dorsal_group == g].site.nunique()))
                           for g in ("ventral", "dorsal", "outside")}
    C["gradient_fig3d"]["in_mask_total"] = dict(
        cells=int(gr.in_gradient_mask.sum()),
        sites=int(gr[gr.in_gradient_mask.astype(bool)].site.nunique()))
    rc = pd.read_csv(SRC["ripple_content"])
    C["ripple_content_fig4h_sessions"] = {r: int(n) for r, n in rc.groupby("roi").session.nunique().items()}
    return C


def markdown(C):
    a = C["all"]
    other = ", ".join(f"{k} {v}" for k, v in a["other_by_label"].items())
    sites = ", ".join(f"{k} {v} patients / {a['sessions_per_site'][k]} sessions"
                      for k, v in a["patients_per_site"].items())
    L = [f"# Human single-unit counts (generated {datetime.date.today()})", "",
         "Generated by `scripts/cell_counts_summary.py` from the tables the reported "
         "analyses read. Do not edit by hand; rerun the script.", "",
         f"**ROI labels:** `{os.path.relpath(FINAL_ROI_TABLE, D)}`, column `{ROI_COLUMN}` "
         "(`neurons_with_ROI_labels.csv` → `alt_final_roi` is the same for the six analysis ROIs). "
         "Old label tables are in `_archive_old_labels_2026-11-23/`.", "",
         "## Cohort", "",
         f"- {a['qc_units']:,} units passing QC; **{a['in_analysis_rois']} in the six analysis ROIs**; "
         f"{a['other']} elsewhere ({other}).",
         f"- **{a['sessions']} sessions from {a['patients']} patients** ({sites}).",
         "", "## Per ROI", "",
         "| ROI | all cells (Fig 2c) | sessions | RSA cells (Fig 2d) | RSA sessions | per-lag cells (Fig 3c) | per-lag sessions | ripple content sessions (Fig 4h) |",
         "|---|---|---|---|---|---|---|---|"]
    for r in ROIS:
        p, s, q = C["per_roi"].get(r, {}), C["rsa_fig2d"].get(r, {}), C["per_lag_fig3c"].get(r, {})
        L.append(f"| {NAMES[r]} | {p.get('cells', '–')} | {p.get('sessions', '–')} | "
                 f"{s.get('cells', '–')} | {s.get('sessions', '–')} | {q.get('cells', '–')} | "
                 f"{q.get('sessions', '–')} | {C['ripple_content_fig4h_sessions'].get(r, '–')} |")
    t = C["rsa_fig2d"]["total"]
    L += ["", f"RSA total: {t['cells']} cells, {t['sessions']} sessions "
          "(EC contributes 3 cells from one session and is not tested). "
          f"Ripple content, HC_all: {C['ripple_content_fig4h_sessions'].get('HC_all')} sessions.",
          "", "## Fig 3d (mPFC cells vs the fMRI gradient)", "",
          "| group | cells | sessions | recording sites |", "|---|---|---|---|"]
    for g in ("ventral", "dorsal", "outside"):
        x = C["gradient_fig3d"][g]
        L.append(f"| {g} | {x['cells']} | {x['sessions']} | {x['sites']} |")
    m = C["gradient_fig3d"]["in_mask_total"]
    L += ["", f"Inside the gradient mask: {m['cells']} cells on {m['sites']} sites.", "",
          "## Sources", ""] + [f"- {k}: `{os.path.relpath(v, D)}`" for k, v in SRC.items()]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    C = counts()
    json.dump(C, open(os.path.join(D, "cell_counts.json"), "w"), indent=1)
    open(os.path.join(D, "CELL_COUNTS.md"), "w").write(markdown(C))
    print(markdown(C))
